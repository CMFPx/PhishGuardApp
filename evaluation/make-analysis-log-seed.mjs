// Runs the labelled evaluation sets through the real rules and writes one SQL
// file that loads the results into the analysis_log table (source = evaluation).
// Rows that have the same score and rules are grouped and repeated with
// generate_series, so the file stays short. Message text is never stored.
// Run: node make-analysis-log-seed.mjs  (Node 22.18 or newer)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { analyzeStatic, scoreIndicators, riskLevel } from "../supabase/functions/analyze/rules.ts";

const here = path.dirname(fileURLToPath(import.meta.url));
const data = (f) => path.join(here, "data", f);
const json = (f) => JSON.parse(fs.readFileSync(data(f), "utf8"));
const lines = (f) => fs.readFileSync(data(f), "utf8").split(/\r?\n/).filter(Boolean);

const legit = json("legit.json");
const sets = [
  { batch: "openphish-2026-10-16-urls", expected: true, items: lines("raw-2026-10-16.txt") },
  { batch: "phishtank-2026-10-16-domains", expected: true, items: json("sample-2026-10-16-phishtank.json").phishing },
  { batch: "openphish-2026-09-24-domains", expected: true, items: json("sample-2026-09-24.json").phishing },
  { batch: "legitimate-domains", expected: false, items: Object.values(legit).filter(Array.isArray).flat() },
];

const groups = new Map();
const summary = [];
for (const s of sets) {
  let flagged = 0;
  for (const item of s.items) {
    const ind = analyzeStatic(item);
    const score = scoreIndicators(ind);
    const rules = [...new Set(ind.filter((i) => i.level !== "neutral").map((i) => i.title))].sort();
    if (score >= 30) flagged++;
    const key = JSON.stringify([s.batch, s.expected, score, rules]);
    groups.set(key, (groups.get(key) || 0) + 1);
  }
  summary.push(`${s.batch.padEnd(32)} ${String(s.items.length).padStart(4)} checked, ${flagged} scored 30 or more (${((100 * flagged) / s.items.length).toFixed(1)}%)`);
}

const q = (str) => "'" + str.replace(/'/g, "''") + "'";
const rows = [...groups.entries()].map(([k, n]) => {
  const [batch, expected, score, rules] = JSON.parse(k);
  const arr = rules.length ? `array[${rules.map(q).join(",")}]::text[]` : "'{}'::text[]";
  return `  (${q(batch)}, ${expected}, ${score}, ${q(riskLevel(score))}, ${arr}, ${n})`;
});

const sql = `-- Loads labelled evaluation results into analysis_log (source = evaluation).
-- Generated by evaluation/make-analysis-log-seed.mjs. Rows are stamped with the
-- time this script is run, which is when the checks were really made.
-- Re-running adds the rows again, so run it once.
insert into analysis_log (source, batch, expected_phishing, score, risk_level, rules)
select 'evaluation', v.batch, v.expected, v.score, v.risk, v.rules
from (values
${rows.join(",\n")}
) as v(batch, expected, score, risk, rules, n)
cross join lateral generate_series(1, v.n);
`;
const out = path.join(here, "..", "supabase", "seed", "analysis_log_evaluation.sql");
fs.writeFileSync(out, sql);
console.log(summary.join("\n"));
console.log(`\n${[...groups.values()].reduce((a, b) => a + b, 0)} rows in ${groups.size} groups -> ${path.relative(process.cwd(), out)}`);
